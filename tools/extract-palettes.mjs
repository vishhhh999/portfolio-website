/**
 * C4: each proof's own palette for the colour bar beside it. For every case-study image (and each
 * video's poster frame), at build time: k-means (k = 8, k-means++ with a fixed seed) in OKLab on
 * the full-colour file (the AVIF re-encoded from the master where one exists, else the WebP),
 * weighted by area. Clusters under 1.5% of the image are dropped, near-duplicates (ΔE_OK < 0.04)
 * merged, then 6 to 8 swatches ordered by lightness. Nothing generic, nothing invented.
 *
 *   node tools/extract-palettes.mjs        → content/palettes.ts
 */
import sharp from 'sharp';
import { readdirSync, existsSync, writeFileSync } from 'fs';
const PUB = new URL('../public/', import.meta.url).pathname;
const OUT = new URL('../content/palettes.ts', import.meta.url).pathname;

const srgbToLin = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const linToSrgb = (c) => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);
function toOklab(r, g, b) {
  const R = srgbToLin(r / 255), G = srgbToLin(g / 255), B = srgbToLin(b / 255);
  const l = Math.cbrt(0.4122214708 * R + 0.5363325363 * G + 0.0514459929 * B);
  const m = Math.cbrt(0.2119034982 * R + 0.6806995451 * G + 0.1073969566 * B);
  const s = Math.cbrt(0.0883024619 * R + 0.2817188376 * G + 0.6299787005 * B);
  return [0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s, 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s, 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s];
}
function toHex([L, a, b]) {
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const rgb = [4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s, -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s, -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s];
  return '#' + rgb.map((c) => Math.round(Math.min(1, Math.max(0, linToSrgb(c))) * 255).toString(16).padStart(2, '0')).join('').toUpperCase();
}
const d2 = (p, q) => (p[0] - q[0]) ** 2 + (p[1] - q[1]) ** 2 + (p[2] - q[2]) ** 2;

function kmeans(pts, k) {
  let seed = 7;
  const rnd = () => ((seed = (seed * 16807) % 2147483647) / 2147483647);
  const cs = [pts[Math.floor(rnd() * pts.length)].slice()];
  while (cs.length < k) {
    const dist = pts.map((p) => Math.min(...cs.map((c) => d2(p, c))));
    const sum = dist.reduce((a, b) => a + b, 0);
    let r = rnd() * sum, i = 0;
    while (i < pts.length - 1 && (r -= dist[i]) > 0) i++;
    cs.push(pts[i].slice());
  }
  const lab = new Array(pts.length).fill(0);
  for (let it = 0; it < 30; it++) {
    for (let i = 0; i < pts.length; i++) {
      let best = 0, bd = Infinity;
      for (let j = 0; j < k; j++) {
        const d = d2(pts[i], cs[j]);
        if (d < bd) (bd = d), (best = j);
      }
      lab[i] = best;
    }
    const acc = cs.map(() => [0, 0, 0, 0]);
    pts.forEach((p, i) => {
      const a = acc[lab[i]];
      a[0] += p[0], a[1] += p[1], a[2] += p[2], a[3]++;
    });
    acc.forEach((a, j) => a[3] && (cs[j] = [a[0] / a[3], a[1] / a[3], a[2] / a[3]]));
  }
  const counts = cs.map(() => 0);
  lab.forEach((j) => counts[j]++);
  return cs.map((c, j) => ({ c, w: counts[j] / pts.length }));
}

async function palette(file) {
  const { data, info } = await sharp(file).resize({ width: 120, height: 120, fit: 'inside' }).removeAlpha().raw().toBuffer({ resolveWithObject: true });
  const pts = [];
  for (let i = 0; i < data.length; i += info.channels) pts.push(toOklab(data[i], data[i + 1], data[i + 2]));
  let cl = kmeans(pts, 8).filter((x) => x.w >= 0.015).sort((a, b) => b.w - a.w);
  // merge near-duplicates into the larger cluster
  const out = [];
  for (const x of cl) {
    const near = out.find((y) => Math.sqrt(d2(x.c, y.c)) < 0.04);
    if (near) near.w += x.w;
    else out.push({ ...x });
  }
  return out.slice(0, 8).sort((a, b) => b.c[0] - a.c[0]).map((x) => ({ hex: toHex(x.c), share: +x.w.toFixed(3) }));
}

const result = {};
for (const slug of readdirSync(PUB + 'work').sort()) {
  for (const f of readdirSync(`${PUB}work/${slug}`).sort()) {
    if (!f.endsWith('.webp') || f.includes('-fluor')) continue;
    const web = `/work/${slug}/${f}`;
    // a video's palette comes from its poster frame; the key is the poster path
    const avif = `${PUB}work/${slug}/${f.replace('.webp', '.avif')}`;
    result[web] = await palette(existsSync(avif) ? avif : `${PUB}work/${slug}/${f}`);
  }
}
const body = Object.entries(result)
  .map(([k, v]) => `  ${JSON.stringify(k)}: [${v.map((x) => `{ hex: '${x.hex}', share: ${x.share} }`).join(', ')}],`)
  .join('\n');
writeFileSync(
  OUT,
  `/**\n * Generated by tools/extract-palettes.mjs: each case-study image's own palette (k-means in OKLab on the\n * full-colour file, weighted by area, ordered by lightness). Keyed by the image's WebP path (a video by its poster).\n */\nexport type Swatch = { hex: string; share: number };\nexport const PALETTES: Record<string, Swatch[]> = {\n${body}\n};\n`,
);
const counts = Object.values(result).map((v) => v.length);
console.log(`${counts.length} images → content/palettes.ts (${Math.min(...counts)}–${Math.max(...counts)} swatches each)`);
